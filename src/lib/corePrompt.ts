/** جداکنندهٔ زنجیر پرامپتها */
const PROMPT_CHAIN = '\n\n---\n\n'

/**
 * پرامپت نهایی که به مدل ارسال میشود:
 * قفل + (در صورت وجود) پرامپت شخصیسازیشدهٔ کاربر از تنظیمات
 */
export function buildSystemPrompt(userPrompt?: string): string {
  const user = userPrompt?.trim()
  return user ? `${CORE_PROMPT}${PROMPT_CHAIN}${user}` : CORE_PROMPT
}

